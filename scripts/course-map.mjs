#!/usr/bin/env node
/**
 * Generates the course map from the site's own data, so the numbers in
 * README.md and docs/course-map.md cannot drift from what the site publishes.
 *
 *   node scripts/course-map.mjs           rewrite both files
 *   node scripts/course-map.mjs --check   exit 1 if either is stale
 *
 * Inputs are src/dashboard/src/data/courses.ts and stats.ts, nothing else.
 * stats.ts is itself checked against a fresh `lmucs stats --json` by
 * tests/site-data.test.mjs, which also runs the --check half of this script.
 *
 * docs/course-map.md is written whole. In README.md only the text between the
 * two course-map markers is replaced.
 *
 * Needs Node 22.18 or later, which imports the .ts data files directly.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = (name) => import(pathToFileURL(path.join(root, 'src/dashboard/src/data', name)).href);

export const START = '<!-- course-map:start (generated by scripts/course-map.mjs) -->';
export const END = '<!-- course-map:end -->';

const SEASONS = { Spring: 0, Summer: 1, Fall: 2 };
/** "Summer 2024 I" -> a number that sorts terms in calendar order. */
export const termOrder = (term) => {
  const [season, year] = term.split(' ');
  return Number(year) * 10 + SEASONS[season];
};

const n = (value) => value.toLocaleString('en-US');
const dir = (course) => `src/courses/${course.slug}`;

export async function build() {
  const { courses } = await data('courses.ts');
  const { languages, linesByCourse, totalLines } = await data('stats.ts');

  const byTerm = [...courses].sort(
    (a, b) => termOrder(a.term) - termOrder(b.term) || a.code.localeCompare(b.code),
  );
  const terms = [...new Set(byTerm.map((c) => c.term))];
  const lines = new Map(linesByCourse.map((c) => [c.course, new Map(c.languages.map((l) => [l.name, l.lines]))]));
  const courseTotal = (code) => [...(lines.get(code)?.values() ?? [])].reduce((a, b) => a + b, 0);
  const withCode = courses.filter((c) => lines.has(c.code));

  /** Course table. `up` is the path prefix back to the repository root. */
  const courseTable = (up) => [
    '| Term | Course | Title | Lines | Languages |',
    '|---|---|---|---:|---|',
    ...byTerm.map((c) => {
      const per = lines.get(c.code);
      const langs = per ? [...per.keys()].join(', ') : '';
      return `| ${c.term} | [${c.code}](${up}${dir(c)}) | ${c.title} | ${per ? n(courseTotal(c.code)) : ''} | ${langs} |`;
    }),
  ];

  const short = (code) => code.replace('CMSI ', '');
  const matrix = [
    `| Language | ${withCode.map((c) => short(c.code)).join(' | ')} | Total |`,
    `|---|${withCode.map(() => '---:').join('|')}|---:|`,
    ...languages.map(
      (l) =>
        `| ${l.name} | ${withCode.map((c) => (lines.get(c.code).has(l.name) ? n(lines.get(c.code).get(l.name)) : '')).join(' | ')} | ${n(l.lines)} |`,
    ),
    `| **Total** | ${withCode.map((c) => `**${n(courseTotal(c.code))}**`).join(' | ')} | **${n(totalLines)}** |`,
  ];

  const summary =
    `${courses.length} courses over ${terms.length} terms, ${terms[0]} to ${terms.at(-1)}. ` +
    `${withCode.length} of them hold counted code: ${n(totalLines)} lines in ${languages.length} languages.`;

  const matrixNote =
    'Lines in tracked files under `src/courses`, by course directory, lockfiles excluded. ' +
    'Columns are CMSI course numbers. Counted by `lmucs stats`; an empty cell means no file in that language.';

  const timeline = [
    '```mermaid',
    'timeline',
    `    title CMSI courses by term, ${terms[0]} to ${terms.at(-1)}`,
    ...terms.map(
      (term) =>
        `    ${term} : ${byTerm.filter((c) => c.term === term).map((c) => `${c.code} ${c.title}`).join(' : ')}`,
    ),
    '```',
  ];

  const doc = [
    '# Course map',
    '',
    'Generated by `scripts/course-map.mjs` from `src/dashboard/src/data/courses.ts` and',
    '`stats.ts`. Do not edit by hand: run `node scripts/course-map.mjs` instead. A test in',
    '`tests/site-data.test.mjs` fails when this file is stale.',
    '',
    summary,
    '',
    '## Timeline',
    '',
    ...timeline,
    '',
    '## Courses by term',
    '',
    ...courseTable('../'),
    '',
    'Lines are blank where the course directory holds no counted code. CMSI 4071 produced a',
    'specification, filed with CMSI 4072.',
    '',
    '## Language by course',
    '',
    matrixNote,
    '',
    ...matrix,
    '',
    "CMSI 3300's Python is the instructor's grading harness. The submitted solutions it",
    'imports are kept in a git bundle outside this repository; see [`building.md`](building.md).',
    '',
  ].join('\n');

  const block = [
    START,
    summary,
    '',
    ...courseTable(''),
    '',
    ...timeline,
    '',
    '<details>',
    `<summary>Language by course: lines in each of the ${languages.length} languages, per course</summary>`,
    '',
    matrixNote,
    '',
    ...matrix,
    '',
    '</details>',
    END,
  ].join('\n');

  return { doc, block };
}

/** README.md with the generated block swapped in. Throws if the markers are missing. */
export function withBlock(readme, block) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error('README.md is missing the course-map markers');
  return readme.slice(0, a) + block + readme.slice(b + END.length);
}

/** Names of the files whose committed text differs from a fresh generation. */
export async function stale() {
  const { doc, block } = await build();
  const docPath = path.join(root, 'docs/course-map.md');
  const readmePath = path.join(root, 'README.md');
  const out = [];
  if (!fs.existsSync(docPath) || fs.readFileSync(docPath, 'utf8') !== doc) out.push('docs/course-map.md');
  const readme = fs.readFileSync(readmePath, 'utf8');
  if (withBlock(readme, block) !== readme) out.push('README.md');
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const files = await stale();
    if (files.length > 0) {
      console.error(`stale: ${files.join(', ')}. Run: node scripts/course-map.mjs`);
      process.exit(1);
    }
    console.log('course map is current');
  } else {
    const { doc, block } = await build();
    fs.writeFileSync(path.join(root, 'docs/course-map.md'), doc);
    const readmePath = path.join(root, 'README.md');
    fs.writeFileSync(readmePath, withBlock(fs.readFileSync(readmePath, 'utf8'), block));
    console.log('wrote docs/course-map.md and the course map in README.md');
  }
}
