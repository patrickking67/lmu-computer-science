"""Count lines of coursework by language.

The dashboard publishes a language breakdown on its front page. Numbers on a
portfolio are worth nothing if nobody can reproduce them, so this is the thing
that produces them, and ``tests/site-data.test.mjs`` in the repository root
re-runs the same count and fails the build when the published figures drift.

Only tracked files are counted, so an untracked scratch file cannot inflate a
total, and lockfiles are excluded because a generated 12,000-line
``package-lock.json`` is not coursework by any reading.
"""

from __future__ import annotations

import subprocess
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

#: Extension to display name. Anything not listed here is not counted: prose,
#: PDFs, images, and configuration are all real work but they are not code.
LANGUAGES: dict[str, str] = {
    "js": "JavaScript", "jsx": "JavaScript", "mjs": "JavaScript", "cjs": "JavaScript",
    "ts": "TypeScript", "tsx": "TypeScript",
    "py": "Python",
    "java": "Java",
    "rs": "Rust",
    "c": "C", "h": "C",
    "cpp": "C++", "cc": "C++", "hpp": "C++",
    "swift": "Swift",
    "go": "Go",
    "hs": "Haskell",
    "kt": "Kotlin",
    "lua": "Lua",
    "ml": "OCaml", "mli": "OCaml",
    "ohm": "Ohm",
    "csc": "CloudScribe",
    "html": "HTML",
    "css": "CSS",
    "asm": "Assembly", "s": "Assembly",
    "sh": "Shell", "bash": "Shell",
}

#: Generated by a package manager, not written by anyone.
EXCLUDED_NAMES = frozenset({"package-lock.json", "Cargo.lock", "yarn.lock"})


@dataclass(frozen=True)
class LanguageCount:
    name: str
    lines: int

    def __str__(self) -> str:  # pragma: no cover - formatting only
        return f"{self.name}: {self.lines}"


def tracked_files(root: Path, subtree: str = "src/courses") -> list[Path]:
    """Every file git tracks under ``subtree``.

    Falls back to a filesystem walk outside a git checkout, so the count still
    works from an extracted archive.
    """
    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", subtree],
            capture_output=True, check=True, text=True,
        ).stdout
        return [root / p for p in out.split("\0") if p]
    except (OSError, subprocess.CalledProcessError):
        return [p for p in (root / subtree).rglob("*") if p.is_file()]


def _line_totals(root: Path, subtree: str) -> Counter[tuple[str, str]]:
    """Lines keyed by (course directory, language) for every counted file."""
    totals: Counter[tuple[str, str]] = Counter()
    base = root / subtree
    for path in tracked_files(root, subtree):
        if path.name in EXCLUDED_NAMES:
            continue
        language = LANGUAGES.get(path.suffix.lstrip(".").lower())
        if language is None:
            continue
        try:
            text = path.read_bytes()
            course = path.relative_to(base).parts[0]
        except (OSError, ValueError, IndexError):
            continue
        totals[(course, language)] += text.count(b"\n")
    return totals


def _largest_first(totals: Counter[str]) -> list[LanguageCount]:
    return [
        LanguageCount(name, lines)
        for name, lines in sorted(totals.items(), key=lambda kv: (-kv[1], kv[0]))
    ]


def count_lines(root: Path, subtree: str = "src/courses") -> list[LanguageCount]:
    """Lines per language, largest first."""
    totals: Counter[str] = Counter()
    for (_course, language), lines in _line_totals(root, subtree).items():
        totals[language] += lines
    return _largest_first(totals)


def count_lines_by_course(
    root: Path, subtree: str = "src/courses"
) -> dict[str, list[LanguageCount]]:
    """Lines per language inside each course directory, courses in name order.

    A course is the first path segment under ``subtree`` (``cmsi-3801``). Summed
    over every course this equals :func:`count_lines`, because both are built
    from the same pass. Courses with no counted code are absent.
    """
    per_course: dict[str, Counter[str]] = {}
    for (course, language), lines in _line_totals(root, subtree).items():
        per_course.setdefault(course, Counter())[language] += lines
    return {course: _largest_first(per_course[course]) for course in sorted(per_course)}


def total_lines(counts: list[LanguageCount]) -> int:
    return sum(c.lines for c in counts)
